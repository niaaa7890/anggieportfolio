document.addEventListener("DOMContentLoaded", () => {
  const $ = (id) => document.getElementById(id);
  const menuToggle = $("menu-toggle");
  const primaryNav = $("primary-nav");
  const navLinks = document.querySelectorAll(".primary-nav a");
  const typingElement = $("typing-text");
  const sections = document.querySelectorAll("main section[id]");
  const backToTop = $("back-to-top");
  const currentYear = $("current-year");
  const reduceMotion = window.matchMedia(
    "(prefers-reduced-motion: reduce)",
  ).matches;

  /* ---------- Helpers ---------- */
  const isVideo = (src) => /\.(mp4|webm|mov|m4v|ogg)$/i.test(src);
  // Removes double slashes and encodes spaces/special characters in file names
  const fileUrl = (src) => encodeURI(src.replace(/\/{2,}/g, "/"));

  /* ---------- Gallery modal (photos + videos) ---------- */
  const modal = $("detail-modal");
  const gMain = document.querySelector(".gallery-main");
  const gImage = $("gallery-image");
  const gThumbs = $("gallery-thumbs");
  const gPrev = $("gallery-prev");
  const gNext = $("gallery-next");
  let photos = [],
    current = 0,
    lastFocus = null;

  const gVideo = document.createElement("video");
  gVideo.controls = true;
  gVideo.playsInline = true;
  gVideo.preload = "metadata";
  gVideo.hidden = true;
  gMain.insertBefore(gVideo, gImage);

  const stopVideo = () => {
    gVideo.pause();
    gVideo.removeAttribute("src");
    gVideo.load();
  };

  const showPhoto = (i) => {
    current = (i + photos.length) % photos.length;
    const src = fileUrl(photos[current]);

    stopVideo();

    if (isVideo(src)) {
      gImage.hidden = true;
      gVideo.hidden = false;
      gVideo.src = src;
      gVideo.load();
    } else {
      gVideo.hidden = true;
      gImage.hidden = false;
      gImage.src = src;
    }

    gThumbs
      .querySelectorAll("button")
      .forEach((b, n) => b.classList.toggle("active", n === current));
  };

  const openModal = (key, index) => {
    const item = DATA[key][index];
    photos = item.gallery && item.gallery.length ? item.gallery : [item.cover];

    $("modal-title").textContent = item.title;
    $("modal-sub").textContent = item.org;
    $("modal-date").textContent = `${item.date} · ${item.type}`;
    $("modal-desc").innerHTML =
      item.desc.length > 1
        ? `<ul>${item.desc.map((d) => `<li>${d}</li>`).join("")}</ul>`
        : `<p>${item.desc[0]}</p>`;
    $("modal-skills").innerHTML = item.skills
      .map((s) => `<span>${s}</span>`)
      .join("");

    gThumbs.innerHTML = "";
    photos.forEach((src, n) => {
      const b = document.createElement("button");
      b.type = "button";
      b.setAttribute(
        "aria-label",
        isVideo(src) ? `Video ${n + 1}` : `Photo ${n + 1}`,
      );
      b.innerHTML = isVideo(src)
        ? '<span class="thumb-video"><i class="fa-solid fa-play" aria-hidden="true"></i></span>'
        : `<img src="${fileUrl(src)}" alt="" loading="lazy" />`;
      b.addEventListener("click", () => showPhoto(n));
      gThumbs.appendChild(b);
    });

    const multi = photos.length > 1;
    gPrev.hidden = !multi;
    gNext.hidden = !multi;
    gThumbs.style.display = multi ? "flex" : "none";
    gImage.alt = item.title;
    showPhoto(0);

    lastFocus = document.activeElement;
    modal.classList.add("open");
    modal.setAttribute("aria-hidden", "false");
    document.body.classList.add("menu-open");
    modal.querySelector(".modal-close").focus();
  };

  const closeModal = () => {
    stopVideo();
    modal.classList.remove("open");
    modal.setAttribute("aria-hidden", "true");
    document.body.classList.remove("menu-open");
    if (lastFocus) lastFocus.focus();
  };

  modal
    .querySelectorAll("[data-close]")
    .forEach((el) => el.addEventListener("click", closeModal));
  gPrev.addEventListener("click", () => showPhoto(current - 1));
  gNext.addEventListener("click", () => showPhoto(current + 1));
  document.addEventListener("keydown", (e) => {
    if (!modal.classList.contains("open")) return;
    if (e.key === "Escape") closeModal();
    if (e.key === "ArrowLeft") showPhoto(current - 1);
    if (e.key === "ArrowRight") showPhoto(current + 1);
  });

  /* ---------- Render cards (seluruh kartu bisa diklik) ---------- */
  const renderGrid = (key) => {
    const grid = $(`${key}-grid`);
    if (!grid) return;

    DATA[key].forEach((item, index) => {
      const card = document.createElement("article");
      card.className = "item-card";
      card.tabIndex = 0;
      card.setAttribute("role", "button");
      card.setAttribute("aria-label", `Open details: ${item.title}`);

      const cover = document.createElement("div");
      cover.className = "item-cover" + (item.isLogo ? " is-logo" : "");
      const img = document.createElement("img");
      img.src = fileUrl(item.cover);
      img.alt = "";
      img.loading = "lazy";
      img.onerror = () => {
        const f = document.createElement("div");
        f.className = "cover-fallback";
        f.textContent = (item.org || "?").trim().charAt(0).toUpperCase();
        img.replaceWith(f);
      };
      cover.appendChild(img);

      const body = document.createElement("div");
      body.className = "item-body";
      body.innerHTML = `
        <span class="type-label">${item.type}</span>
        <span class="date-label">${item.date}</span>
        <h3>${item.title}</h3>
        <h4>${item.org}</h4>
        <p class="summary">${item.summary}</p>
        <div class="tag-list">${item.skills
          .slice(0, 3)
          .map((s) => `<span>${s}</span>`)
          .join("")}</div>
        <div class="item-footer">
          <span class="detail-btn" aria-hidden="true"><i class="fa-solid fa-arrow-right"></i></span>
        </div>`;

      card.append(cover, body);

      card.addEventListener("click", () => openModal(key, index));
      card.addEventListener("keydown", (e) => {
        if (e.key === "Enter" || e.key === " ") {
          e.preventDefault();
          openModal(key, index);
        }
      });

      grid.appendChild(card);
    });
  };

  ["experience", "projects", "organization"].forEach(renderGrid);

  /* ---------- Scroll reveal ---------- */
  if ("IntersectionObserver" in window && !reduceMotion) {
    const revealObserver = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (!entry.isIntersecting) return;
          const el = entry.target;
          el.classList.add("in");
          revealObserver.unobserve(el);
          // Lepas class setelah animasi selesai agar efek hover kartu tetap normal
          setTimeout(() => el.classList.remove("reveal", "in"), 1000);
        });
      },
      { threshold: 0.12 },
    );

    document
      .querySelectorAll(
        ".section-heading, .about-copy, .fact-card, .item-card, .skill-panel, .certificate-card, .contact-item",
      )
      .forEach((el, idx) => {
        el.style.setProperty("--i", idx % 4);
        el.classList.add("reveal");
        revealObserver.observe(el);
      });
  }

  /* ---------- Hero tilt (desktop saja) ---------- */
  const heroVisual = document.querySelector(".hero-visual");
  if (
    heroVisual &&
    !reduceMotion &&
    window.matchMedia("(hover: hover)").matches
  ) {
    const hero = document.querySelector(".hero");
    hero.addEventListener("mousemove", (e) => {
      const r = hero.getBoundingClientRect();
      const x = (e.clientX - r.left) / r.width - 0.5;
      const y = (e.clientY - r.top) / r.height - 0.5;
      heroVisual.style.setProperty("--ry", `${x * 8}deg`);
      heroVisual.style.setProperty("--rx", `${-y * 8}deg`);
    });
    hero.addEventListener("mouseleave", () => {
      heroVisual.style.setProperty("--ry", "0deg");
      heroVisual.style.setProperty("--rx", "0deg");
    });
  }

  /* ---------- Mobile navigation ---------- */
  const closeMenu = () => {
    if (!menuToggle || !primaryNav) return;
    primaryNav.classList.remove("open");
    menuToggle.setAttribute("aria-expanded", "false");
    menuToggle.setAttribute("aria-label", "Open navigation");
    menuToggle.innerHTML =
      '<i class="fa-solid fa-bars" aria-hidden="true"></i>';
    document.body.classList.remove("menu-open");
  };

  if (menuToggle && primaryNav) {
    menuToggle.addEventListener("click", () => {
      const isOpen = primaryNav.classList.toggle("open");
      menuToggle.setAttribute("aria-expanded", String(isOpen));
      menuToggle.setAttribute(
        "aria-label",
        isOpen ? "Close navigation" : "Open navigation",
      );
      menuToggle.innerHTML = isOpen
        ? '<i class="fa-solid fa-xmark" aria-hidden="true"></i>'
        : '<i class="fa-solid fa-bars" aria-hidden="true"></i>';
      document.body.classList.toggle("menu-open", isOpen);
    });

    navLinks.forEach((link) => link.addEventListener("click", closeMenu));

    document.addEventListener("keydown", (e) => {
      if (e.key === "Escape" && primaryNav.classList.contains("open"))
        closeMenu();
    });

    document.addEventListener("click", (e) => {
      if (
        primaryNav.classList.contains("open") &&
        !primaryNav.contains(e.target) &&
        !menuToggle.contains(e.target)
      )
        closeMenu();
    });

    window.addEventListener("resize", () => {
      if (window.innerWidth > 850) closeMenu();
    });
  }

  /* ---------- Typing animation ---------- */
  if (typingElement) {
    const professions = [
      "UI/UX Designer",
      "Frontend Developer",
      "IT Support",
      "Website Management",
      "Digital Marketing",
    ];

    if (reduceMotion) {
      typingElement.textContent = professions[0];
    } else {
      let p = 0,
        c = 0,
        deleting = false;
      const type = () => {
        const word = professions[p];
        c += deleting ? -1 : 1;
        typingElement.textContent = word.slice(0, c);
        let delay = deleting ? 55 : 105;
        if (!deleting && c === word.length) {
          deleting = true;
          delay = 1450;
        } else if (deleting && c === 0) {
          deleting = false;
          p = (p + 1) % professions.length;
          delay = 350;
        }
        setTimeout(type, delay);
      };
      setTimeout(type, 450);
    }
  }

  /* ---------- Active navigation link ---------- */
  if ("IntersectionObserver" in window && sections.length && navLinks.length) {
    const observer = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (!entry.isIntersecting) return;
          navLinks.forEach((link) =>
            link.classList.toggle(
              "active",
              link.getAttribute("href") === `#${entry.target.id}`,
            ),
          );
        });
      },
      { rootMargin: "-35% 0px -55% 0px", threshold: 0 },
    );
    sections.forEach((s) => observer.observe(s));
  }

  /* ---------- Back to top & year ---------- */
  const updateBackToTop = () =>
    backToTop && backToTop.classList.toggle("visible", window.scrollY > 500);
  window.addEventListener("scroll", updateBackToTop, { passive: true });
  updateBackToTop();

  if (currentYear) currentYear.textContent = new Date().getFullYear();
});
